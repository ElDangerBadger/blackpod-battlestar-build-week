"""Strict versioned Brigade member responses with no decision authority.

This is an advisory payload, not an authorization or an executable order.
SHADOW/TRADING and disabled authorities are owned by the containing request
and analysis, rather than generated by a model. Model assertions about those
authorities are unknown fields and are rejected. The response must also bind
to the externally supplied member and symbol before it can contribute a vote.

Raw bytes remain evidence outside this document. Parsing performs no repair,
fence removal, label extraction, coercion, or calibrated-probability inference.
"""
from __future__ import annotations

import json
import math
from decimal import Decimal, DecimalException

from .decision_journal import _enum, _object, _string
from .mission_request import ContractValidationError, parse_strict_json_object_bytes
from .trading_reconciliation import _ReconciliationDocument, symbol_text

SCHEMA_VERSION = "blackpod.brigade_member_response.v1"
MEMBERS = frozenset({
    "Blackwell_Scout", "Blackwell_Sentry", "Blackwell_Advisor",
    "Blackwell_Canary", "Blackwell_Pathfinder",
})
ACTIONS = frozenset({"BUY", "EXIT", "HOLD", "WATCH"})
CONFIDENCE_SEMANTICS = "HEURISTIC_LABEL_NOT_CALIBRATED_PROBABILITY"
MAX_RESPONSE_BYTES = 32 * 1024
MAX_REASONING_CHARACTERS = 4096
MAX_REASONING_BYTES = 16 * 1024
_FIELDS = frozenset({
    "schema_version", "member", "symbol", "action", "heuristic_confidence", "reasoning",
})
# Both native split("\n") parsing and the retained legacy splitlines() gate
# must see exactly the three labels emitted by native_label_projection.
_NON_NATIVE_LINE_SEPARATORS = frozenset({"\u0085", "\u2028", "\u2029"})


def _member(value):
    return _enum(value, MEMBERS, "member")


def _response(value):
    result = _object(value, _FIELDS, "Brigade member response")
    if result["schema_version"] != SCHEMA_VERSION:
        raise ContractValidationError("schema_version must be " + repr(SCHEMA_VERSION))
    result["member"] = _member(result["member"])
    result["symbol"] = symbol_text(result["symbol"])
    result["action"] = _enum(result["action"], ACTIONS, "action")
    confidence = result["heuristic_confidence"]
    if type(confidence) not in (int, float) or not 0 <= confidence <= 1 or not math.isfinite(confidence):
        raise ContractValidationError("heuristic_confidence must be a finite JSON number between zero and one")
    reasoning = _string(result["reasoning"], "reasoning", MAX_REASONING_CHARACTERS)
    if len(reasoning.encode("utf-8")) > MAX_REASONING_BYTES or any(char in _NON_NATIVE_LINE_SEPARATORS for char in reasoning):
        raise ContractValidationError("reasoning must be bounded single-line text")
    result["reasoning"] = reasoning
    return result


def _bounded_bytes(raw):
    if not isinstance(raw, bytes) or not 0 < len(raw) <= MAX_RESPONSE_BYTES:
        raise ContractValidationError("Brigade response must be one bounded nonempty UTF-8 JSON object")
    return raw


class BrigadeMemberResponse(_ReconciliationDocument):
    """Immutable advisory content; external identity binding remains required."""

    __slots__ = ()
    _validator = staticmethod(_response)

    @classmethod
    def from_bytes(cls, value: bytes):
        return cls.from_mapping(_parse_response_json(_bounded_bytes(value)))

    @property
    def confidence_is_probability(self):
        return False


def validate_member_response(value, *, expected_member, expected_symbol):
    """Validate the six fields and bind them to the caller's request identity."""
    member, symbol = _member(expected_member), symbol_text(expected_symbol)
    response = _response(value)
    if response["member"] != member or response["symbol"] != symbol:
        raise ContractValidationError("Brigade response member/symbol differs from its expected request identity")
    return response


def _parse_response_json(raw):
    try:
        value = parse_strict_json_object_bytes(raw, document_name="Brigade member response")
        # A raw JSON decimal just outside [0, 1] must not round into that
        # interval before the bound check. The ordinary typed document keeps
        # repository JSON number conventions; original text stays evidence.
        exact = json.loads(raw, parse_float=Decimal).get("heuristic_confidence")
        if type(exact) in (int, Decimal) and not 0 <= exact <= 1:
            raise ContractValidationError("heuristic_confidence literal is outside zero and one")
    except (RecursionError, ValueError, OverflowError, DecimalException) as exc:
        if isinstance(exc, ContractValidationError):
            raise
        raise ContractValidationError("Brigade response JSON exceeds supported parser limits") from exc
    return value


def parse_member_response(raw, *, expected_member, expected_symbol):
    """Parse exactly one object, preserving typed values without any repair."""
    if isinstance(raw, str):
        try:
            raw = raw.encode("utf-8")
        except UnicodeEncodeError as exc:
            raise ContractValidationError("Brigade response must be valid UTF-8") from exc
    value = _parse_response_json(_bounded_bytes(raw))
    return BrigadeMemberResponse.from_mapping(validate_member_response(
        value, expected_member=expected_member, expected_symbol=expected_symbol,
    ))


def response_json_schema(expected_member, expected_symbol):
    """Return the exact per-request constrained-output schema; parser is final."""
    member, symbol = _member(expected_member), symbol_text(expected_symbol)
    return {
        "type": "object", "additionalProperties": False,
        "properties": {
            "schema_version": {"type": "string", "const": SCHEMA_VERSION},
            "member": {"type": "string", "const": member},
            "symbol": {"type": "string", "const": symbol},
            "action": {"type": "string", "enum": sorted(ACTIONS)},
            "heuristic_confidence": {"type": "number", "minimum": 0, "maximum": 1},
            # Current ModelDock supports these length bounds, but not pattern.
            # Control characters/whitespace are rejected by the local parser.
            "reasoning": {"type": "string", "minLength": 1, "maxLength": MAX_REASONING_CHARACTERS},
        },
        "required": sorted(_FIELDS),
    }


def native_label_projection(response):
    """Render validated advisory fields for the source-pinned native parser.

    Exactly three labels are emitted. Reasoning cannot contain line separators,
    so text such as 'ACTION: EXIT' inside reasoning cannot change the vote. The
    original structured response and exact reasoning are retained separately.
    """
    if not isinstance(response, BrigadeMemberResponse):
        raise ContractValidationError("native label projection requires a validated BrigadeMemberResponse")
    value = response.to_mapping()
    return "ACTION: " + value["action"] + "\nCONFIDENCE: " + repr(value["heuristic_confidence"]) + "\nREASONING: " + value["reasoning"]
